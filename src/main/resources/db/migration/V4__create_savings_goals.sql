-- Savings goals. Progress is computed from transactions at read time and is never stored.
CREATE TABLE savings_goals (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT                   NOT NULL,
    goal_name     VARCHAR(100)             NOT NULL,
    target_amount NUMERIC(15, 2)           NOT NULL,
    target_date   DATE                     NOT NULL,
    start_date    DATE                     NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_savings_goals_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_savings_goals_target_positive CHECK (target_amount > 0),
    CONSTRAINT ck_savings_goals_dates CHECK (start_date < target_date)
);

CREATE INDEX idx_savings_goals_user ON savings_goals (user_id);
