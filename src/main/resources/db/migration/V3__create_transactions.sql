-- Financial transactions. The type (INCOME/EXPENSE) is derived from the category and is not stored,
-- so it can never disagree with the category. Foreign keys use the default NO ACTION behaviour:
-- deleting a referenced category fails instead of cascading to financial records.
CREATE TABLE transactions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT                   NOT NULL,
    category_id      BIGINT                   NOT NULL,
    amount           NUMERIC(15, 2)           NOT NULL,
    transaction_date DATE                     NOT NULL,
    description      VARCHAR(255),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_transactions_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_transactions_amount_positive CHECK (amount > 0)
);

-- Listing, filtering, reports and goal progress all filter by owner and date range.
CREATE INDEX idx_transactions_user_date ON transactions (user_id, transaction_date);
-- Category filter for the listing endpoint.
CREATE INDEX idx_transactions_user_category ON transactions (user_id, category_id);
-- Referential check when deleting a category.
CREATE INDEX idx_transactions_category ON transactions (category_id);
