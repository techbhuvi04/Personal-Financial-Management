-- Categories are either system defaults (owner_id IS NULL, is_default = TRUE) shared by every user,
-- or custom categories owned by exactly one user. normalized_name is the trimmed, lower-cased name and
-- backs case-insensitive uniqueness per owner without relying on vendor-specific expression indexes.
CREATE TABLE categories (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(50)              NOT NULL,
    normalized_name VARCHAR(50)              NOT NULL,
    type            VARCHAR(10)              NOT NULL,
    is_default      BOOLEAN                  NOT NULL,
    owner_id        BIGINT,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_categories_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT uk_categories_owner_name UNIQUE (owner_id, normalized_name),
    CONSTRAINT ck_categories_type CHECK (type IN ('INCOME', 'EXPENSE')),
    CONSTRAINT ck_categories_ownership CHECK (
        (is_default = TRUE AND owner_id IS NULL) OR (is_default = FALSE AND owner_id IS NOT NULL)
    )
);

